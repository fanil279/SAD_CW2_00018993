    for w,h in [(375,812),(768,1024),(1440,900)]:
        pg.set_viewport_size({'width':w,'height':h})
        for r in ['catalogue','product/p1','cart','fulfilment','delivery','pickup','schedule','review','payment','orders','profile']:
            pg.goto(f'http://localhost:4173/#/{r}'); pg.wait_for_timeout(120)
            ov=pg.evaluate('document.documentElement.scrollWidth>document.documentElement.clientWidth')
            if ov: print('OVERFLOW',w,r)
            res.append((f'noOverflow {w} {r}',not ov))
        pg.goto('http://localhost:4173/#/catalogue'); pg.screenshot(path=f'/tmp/shot_{w}.png')
