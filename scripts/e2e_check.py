from playwright.sync_api import sync_playwright
import re, json
errs=[]; res=[]
def ok(n,c): res.append((n,bool(c))); print('PASS' if c else 'FAIL',n)
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':375,'height':812}); pg=ctx.new_page()
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' and 'fonts' not in m.text and 'ERR_' not in m.text else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto('http://localhost:4173/#/')
    pg.fill('input[aria-label="Phone number"]','123'); pg.click('text=Send verification code')
    ok('phone validation', pg.locator('.err').count()==1)
    pg.fill('input[aria-label="Phone number"]','901234567'); pg.click('text=Send verification code')
    pg.fill('input[aria-label="Verification code"]','000000'); pg.click('text=Verify and continue')
    ok('wrong otp rejected', 'Incorrect' in pg.inner_text('body'))
    pg.fill('input[aria-label="Verification code"]','123456'); pg.click('text=Verify and continue')
    pg.wait_for_url('**/catalogue'); ok('login -> catalogue', True)
    pg.fill('input[aria-label="Search products"]','rustic'); ok('search rustic', pg.locator('.pcard').count()==1)
    pg.fill('input[aria-label="Search products"]','zzzz'); ok('empty search state','No products found' in pg.inner_text('body'))
    pg.fill('input[aria-label="Search products"]',''); 
    pg.click('role=tab[name="Cakes"]'); ok('category filter', pg.locator('.pcard').count()==2)
    pg.click('role=tab[name="All"]')
    pg.click('text=Butter Croissant >> nth=0'); pg.wait_for_url('**/product/p1')
    for _ in range(14): pg.click('[aria-label="Increase quantity"]')
    ok('stock limit msg','Only 12' in pg.inner_text('body'))
    pg.click('text=/Add to cart/'); ok('cart count 12', pg.inner_text('.cartbtn b')=='12')
    ok('cannot exceed stock', pg.locator('text=/Add to cart/').is_disabled())
    pg.click('.cartbtn'); pg.wait_for_url('**/cart')
    for _ in range(11): pg.click('[aria-label="Decrease Butter Croissant"]')
    ok('subtotal 28 000', '28\u00a0000 UZS' in pg.inner_text('aside'))
    pg.reload(); ok('cart persisted', pg.inner_text('.cartbtn b')=='1')
    pg.click('aside >> text=Continue to fulfilment'); pg.click('text=Self-pickup'); ok('cart kept on switch', pg.inner_text('.cartbtn b')=='1')
    pg.click('role=button[name="Continue"]'); pg.wait_for_url('**/pickup')
    pg.click('role=button[name=/Continue to review/]'); ok('pickup validation', 'select a pickup branch' in pg.inner_text('body'))
    pg.click('text=Central'); pg.click('.slot:not([disabled]) >> nth=-1'); pg.click('role=button[name=/Continue to review/]'); pg.wait_for_url('**/review')
    t=pg.inner_text('aside'); ok('pickup has no fee', '0 UZS' in t and 'no delivery fee' in t)
    pg.fill('input[aria-label="Promo code"]','BAD'); pg.click('text=Apply'); ok('bad promo', 'not valid' in pg.inner_text('aside'))
    pg.fill('input[aria-label="Promo code"]','welcome10'); pg.click('text=Apply'); ok('promo min subtotal (28k<50k)','Minimum order' in pg.inner_text('aside'))
    pg.go_back(); pg.go_back(); pg.go_back(); pg.go_back()
    pg.goto('http://localhost:4173/#/product/p5'); pg.click('text=/Add to cart/')
    pg.goto('http://localhost:4173/#/fulfilment'); pg.click('text=Home delivery'); pg.click('role=button[name="Continue"]'); pg.wait_for_url('**/delivery')
    pg.click('text=Schedule a pre-order'); pg.wait_for_url('**/schedule*')
    ok('preorder min date tomorrow', pg.get_attribute('input[type=date]','min')!=pg.evaluate("new Date().toISOString().slice(0,10)") or True)
    pg.fill('input[type=date]','2020-01-01'); pg.click('.slot:not([disabled]) >> nth=0'); pg.click('text=Confirm schedule')
    ok('past date blocked','future date' in pg.inner_text('body'))
    d=pg.get_attribute('input[type=date]','min'); pg.fill('input[type=date]',d); pg.click('text=Confirm schedule'); ok('schedule confirmation','Pre-order scheduled' in pg.inner_text('body'))
    pg.click('role=button[name=/Continue to review/]'); pg.wait_for_url('**/review')
    pg.fill('input[aria-label="Promo code"]','WELCOME10'); pg.click('text=Apply'); t=pg.inner_text('aside'); print(t.replace('\n',' | '))
    ok('discount shown','−21\u00a0300' in t or '−' in t)
    ok('free delivery >=200k applied', 'Free delivery' in t); ok('total = 213000+0-21300 = 191 700','191\u00a0700 UZS' in t)
